def get_sample_records(organism: str, gene: str):
    """
    Look up sample records matching organism and gene.
    Returns list of records if found, else empty list.
    """
    org_key = organism.strip().lower()
    gene_key = gene.strip().lower()

    # Exact key match
    if (org_key, gene_key) in SAMPLE_DATASETS:
        return SAMPLE_DATASETS[(org_key, gene_key)]

    # Fuzzy / substring match
    for (o, g), records in SAMPLE_DATASETS.items():
        if (org_key in o or o in org_key) and (gene_key in g or g in gene_key):
            return records

    return []

